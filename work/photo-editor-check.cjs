const assert = require('node:assert/strict');
const { webcrypto } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const M = require('./photo-editor/model.js');
const id = 'a18d68c8-062a-4e93-804a-008531027ae2';
(async () => {
  const sourceUrl = 'https://example.supabase.co/storage/v1/object/public/photos/latte.png';
  const entry = { id, name: 'Латте <script>', sourceUrl, sourceFingerprint: await M.fingerprint(sourceUrl, webcrypto), detail: M.defaultView('detail'), card: M.defaultView('card') };
  assert.match(entry.sourceFingerprint, /^url-sha256:[0-9a-f]{64}$/);
  assert.notEqual(entry.sourceFingerprint, await M.fingerprint(sourceUrl + '?v=2', webcrypto));
  assert.deepEqual(M.parseDocument(JSON.stringify(M.documentFor([entry]))), [entry]);
  assert.equal(M.sourceUrl({image_override_url: sourceUrl,image_url:'https://other.example/old'}), sourceUrl);
  assert.equal(M.sourceUrl({image_url:'/photo/1'}), 'https://api.sbis.ru/photo/1');
  assert.equal(M.sourceUrl({image_url:'http://example.com/unsafe'}), null);
  assert.equal(M.sourceUrl({image_url:'https://user:password@example.com/photo'}), null);
  assert.throws(() => M.parseDocument({...M.documentFor([entry]),version:2}));
  assert.throws(() => M.parseDocument({...M.documentFor([entry]),projectRef:'other-project'}));
  assert.throws(() => M.parseDocument({...M.documentFor([entry]),products:[entry, entry]}));
  assert.throws(() => M.validateEntry({...entry,id:'__proto__'}));
  assert.throws(() => M.normalizeView({...entry.detail,zoom:Infinity}));
  assert.throws(() => M.normalizeView({...entry.detail,offsetX:'12'}));
  assert.throws(() => M.normalizeView({...entry.detail,offsetY:36}));
  assert.throws(() => M.normalizeView({...entry.detail,fit:'fill'}));
  const normal = M.geometry(400, 420, 1000, 2000, entry.detail);
  assert.deepEqual(normal, {width:189,height:378,left:105.5,top:21});
  const offset = M.geometry(400,420,1000,2000,{...entry.detail,offsetX:10,offsetY:-10});
  assert.equal(offset.left-normal.left,40);
  assert.equal(offset.top-normal.top,-42);
  const doubled = M.geometry(800,840,1000,2000,{...entry.detail,offsetX:10,offsetY:-10});
  assert.equal(doubled.left,offset.left*2);
  assert.equal(doubled.top,offset.top*2);
  assert.equal(M.isDefault(entry),true);
  assert.equal(M.documentFor([entry]).products.length,1, 'Explicit standard frames remain exportable for reset-by-UUID');
  assert.equal(M.isDefault({...entry,detail:{...entry.detail,zoom:1.08}}),false);
  const editor = fs.readFileSync(path.join(__dirname,'photo-editor/editor.js'),'utf8');
  assert.ok(!/\.innerHTML\b|service_role|\.rpc\(|signIn|Authorization\s*:/.test(editor));
  assert.equal((editor.match(/\bfetch\(/g)||[]).length,1);
  assert.match(editor,/method: 'GET'/);
  assert.match(editor,/credentials: 'omit'/);
  assert.ok(!/raw_payload|customer_phone|bonus_accounts/.test(editor));
  assert.match(editor,/style\.transform = `translate\(/);
  assert.match(editor,/image\.style\.transform = `scale\(/);
  console.log('Photo editor: schema, source guards, geometry, responsive offsets and read-only transport PASS');
})().catch(error => { console.error(error); process.exitCode=1; });
