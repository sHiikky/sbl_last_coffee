const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {derivePhotoPalette}=require('../load-domain.cjs')('work/product-concepts/photo-palette.js');
const fixture=(...parts)=>parts.flatMap(([count,rgba])=>Array.from({length:count},()=>rgba).flat());
const green=derivePhotoPalette(fixture([2500,[255,255,255,255]],[800,[80,80,80,255]],[700,[30,120,35,255]],[96,[0,0,0,0]]));
assert(green.fromPhoto);assert(green.hue>115&&green.hue<130);assert(green.saturation<=42);
const neutral=derivePhotoPalette(fixture([3000,[250,250,250,255]],[1080,[90,90,90,255]],[16,[240,0,0,255]]),{fallback:194});
assert.equal(neutral.fromPhoto,false);assert.equal(neutral.hue,194);
const red=derivePhotoPalette(fixture([2048,[180,15,20,255]],[2048,[180,20,15,255]]));
assert(red.fromPhoto);assert(red.hue<5||red.hue>355,'red across 0/360 stays red');
const purple=derivePhotoPalette(fixture([4096,[200,90,190,255]]),{toneRange:[272,290]});
assert(purple.hue<=290&&purple.hue>=272);
const dark=derivePhotoPalette(fixture([4096,[4,6,8,255]]),{fallback:32});assert.equal(dark.hue,32);
assert.equal(fs.readFileSync(path.resolve(__dirname,'../../theme/holographic.js'),'utf8'),fs.readFileSync(path.join(__dirname,'checkout-holographic-tokens.js'),'utf8'),'prototype uses the exact app tokens');
console.log('PASS: white/metal/transparent exclusion, sparse-reflection fallback, circular red hue, reviewed tone ranges, bounded saturation, exact app holographic tokens');
