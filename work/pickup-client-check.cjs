const assert = require('node:assert/strict');
const load = require('./load-domain.cjs');
const { optionCartKey, makeCartItem, canonicalModifiers, cartMatchesSnapshot, normalizePreparationNote, compareCartKeys } = load('lib/cartOptions.js');
const { buildCheckoutQuote, refreshCartPrices } = load('lib/checkoutQuote.js');
const { normalizeContactPhone, validateContact, getLocalOrderingState, orderingState } = load('lib/ordering.js', { './supabaseClient': { supabase: {} } });
const product = { id: 'p', name: 'Кофе', price: 200, isAvailable: true };
const milk = { id: 'm', quantity: 2, unitPrice: 15, name: 'Молоко' };
const syrup = { id: 's', quantity: 1, unitPrice: 30, name: 'Сироп' };
const a = makeCartItem(product, [syrup, milk], 2);
assert.equal(a.unitPrice, 260);
assert.equal(a.key, 'p|mx2|sx1');
assert.equal(optionCartKey('p', [milk, syrup]), a.key);
assert.notEqual(makeCartItem(product).key, a.key);
assert.notEqual(makeCartItem(product, [{ ...milk, quantity: 1 }]).key, a.key);
const vanilla = makeCartItem(product, [syrup], 1, 'Ваниль');
const cherry = makeCartItem(product, [syrup], 1, 'Вишня');
assert.notEqual(vanilla.key, cherry.key, 'flavors of the same generic syrup stay separate');
assert.equal(buildCheckoutQuote([vanilla, cherry], 460).items.length, 2);
assert.equal(normalizePreparationNote(' \tВаниль\r\nбез льда \n'), 'Ваниль\nбез льда');
assert.throws(() => normalizePreparationNote('x'.repeat(201)));
assert.throws(() => normalizePreparationNote('vanilla\u0000'));
assert.equal(compareCartKeys('\uE000', '😀') < 0, true, 'Unicode keys follow PostgreSQL byte order rather than JS UTF16 order');
assert.equal(cartMatchesSnapshot({ [a.key]: a }, [a]), true);
assert.equal(cartMatchesSnapshot({ [a.key]: { ...a, qty: 3 } }, [a]), false, 'new quantity must survive a late recovery response');
assert.equal(cartMatchesSnapshot({ [a.key]: a, p: makeCartItem(product) }, [a]), false, 'new recipe must survive recovery');
assert.throws(() => canonicalModifiers([{ ...milk, quantity: 0 }]));
assert.throws(() => canonicalModifiers([milk, milk]));
assert.throws(() => canonicalModifiers(Array.from({ length: 21 }, (_, i) => ({ id: `m${i}`, quantity: 1 }))));
const q = buildCheckoutQuote([a, makeCartItem(product, [milk, syrup])], 780);
assert.equal(q.version, 2);
assert.equal(JSON.stringify(q.items), JSON.stringify([['p|mx2|sx1','p',3,200,[['m',2,15],['s',1,30]]]]));
const catalog = [product, { id: 'm', price: 20, isModifier: true, isAvailable: true, name: 'Молоко' }, { id: 's', price: 30, isModifier: true, isAvailable: true, name: 'Сироп' }];
assert.equal(refreshCartPrices({ [a.key]: a }, catalog)[a.key].unitPrice, 270);
assert.equal(Object.keys(refreshCartPrices({ [a.key]: a }, catalog.slice(0, 2))).length, 0, 'missing addition must not silently alter recipe');
assert.equal(a.unitPrice, 260, 'refresh does not mutate existing item');
assert.equal(normalizeContactPhone('8 (999) 000-00-01'), '+79990000001');
assert.equal(normalizeContactPhone('9990000001'), '+79990000001');
assert.equal(normalizeContactPhone('+1 999 000 0001'), null);
assert.throws(() => validateContact({ name: '', phone: '+79990000001' }));
assert.equal(validateContact({ name: ' Тест ', phone: '89990000001' }).name, 'Тест');
const isOpen = iso => getLocalOrderingState(new Date(iso)).isOpen;
assert.equal(isOpen('2026-10-29T03:59:59Z'), false, '10:59:59 Tomsk');
assert.equal(isOpen('2026-10-29T04:00:00Z'), true, '11:00 Tomsk');
assert.equal(isOpen('2026-10-29T12:55:00Z'), true, '19:55 Tomsk');
assert.equal(isOpen('2026-10-29T12:55:01Z'), false, '19:55:01 Tomsk');
assert.equal(isOpen('2026-10-29T13:00:00Z'), false, '20:00 Tomsk');
assert.equal(orderingState({ server_now: '2026-10-29T04:00:00Z', receivedAt: 1000 }, 2000).isOpen, true, 'server clock corrects arbitrary phone clock');
console.log('PASS: distinct recipes, canonical additions, server quote v2, stopped additions, contact and Tomsk closing boundaries');
