-- products-schema-update-2.sql
-- Дополнение к supabase-products-schema.sql. Делает две вещи:
--   1. Колонка image_override_url — ручное фото товара (см. предыдущее
--      сообщение), синхронизация из СБИС её не трогает.
--   2. Колонка subcategory — прямая родительская папка товара в СБИС,
--      если между товаром и верхнеуровневой категорией ("Сытное/Десерты" и
--      т.д.) есть промежуточная папка ("Десерты", "Выпечка", "Сэндвичи"...).
--      Если товар лежит прямо в верхнеуровневой категории — subcategory
--      будет равен category. Это НЕ замена category (она по-прежнему решает,
--      входит ли товар в 4 проверенных раздела меню), а дополнительное поле
--      для более дробной навигации внутри раздела — как только пересинхронизируем
--      каталог и увидите реальные значения, решим вместе, стоит ли строить
--      по нему отдельные фильтры/вкладки в приложении.
--   3. Заодно сразу скрывает 3 уже загруженных товара-добавки
--      ("+ конфитюр 40 гр", "+ сыр 20 гр", "+ хлеб 1 кус") — раньше они
--      случайно попали в меню как отдельные позиции.
--
-- Как применить: Supabase Dashboard -> SQL Editor -> вставить целиком -> Run.
-- Безопасно запускать повторно.

alter table public.products
  add column if not exists image_override_url text;

comment on column public.products.image_override_url is
  'Ручная ссылка на фото товара. Если задана — приложение показывает её вместо фото из СБИС. Синхронизация эту колонку не трогает.';

alter table public.products
  add column if not exists subcategory text;

comment on column public.products.subcategory is
  'Прямая родительская папка товара в СБИС (может совпадать с category, если под-папки нет). Заполняется синхронизацией, только для чтения/анализа на данный момент.';

-- Разовая правка: добавки, которые СБИС называет с префиксом "+ ",
-- не должны быть видны как отдельные позиции меню.
update public.products
set is_visible = false
where name ~ '^\+\s' and is_visible = true;
